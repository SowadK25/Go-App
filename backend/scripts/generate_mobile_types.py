"""Generate mobile response types from FastAPI OpenAPI without running a server."""
import argparse
import json
import os
from pathlib import Path
import sys

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
# Schema generation needs no network, Redis, or real API credentials.
os.environ["CACHE_BACKEND"] = "memory"
os.environ["METROLINX_API_KEY"] = "schema-generation-only"
from app.main import app  # noqa: E402


def ts_type(schema):
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + separator.join(ts_type(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)};'
                  for name, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties")
        if additional:
            fields.append(f"[key: string]: {ts_type(additional) if isinstance(additional, dict) else 'unknown'};")
        return "{ " + " ".join(fields) + " }" if fields else "Record<string, unknown>"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    raise ValueError(f"Unsupported OpenAPI schema: {schema}")


def generate():
    schema = app.openapi()
    lines = ["// Generated by backend/scripts/generate_mobile_types.py. Do not edit.", ""]
    for name, definition in sorted(schema["components"]["schemas"].items()):
        lines.append(f"export type {name} = {ts_type(definition)};")
    lines.extend(["", "export interface GetResponses {"])
    for path, operations in sorted(schema["paths"].items()):
        operation = operations.get("get")
        if operation:
            response = operation["responses"]["200"]["content"]["application/json"]["schema"]
            lines.append(f"  {json.dumps(path)}: {ts_type(response)};")
    lines.extend(["}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = BACKEND.parent / "mobile/src/api/generated.ts"
    content = generate()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            sys.exit("Mobile API types are outdated. Run npm.cmd run api:generate in mobile.")
        print("Mobile API types match OpenAPI.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"Generated {target.name}")
